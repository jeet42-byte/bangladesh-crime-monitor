"""Paper 1 data mining: bibliometrics, topic modelling, keyword network and gap tests.

    python scripts/mining.py     (run from research/scoping-review/)

Corpus = included records:
  Tier A (Bangladesh): records charted 'include' at full-text or abstract stage
  Tier B (rest of South Asia): records taken forward (include/maybe) at screening
Outputs: figures/*.png and mining_results.md
"""
import csv, json, re, collections, itertools, os
import numpy as np, pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import networkx as nx
from scipy.stats import chi2_contingency, fisher_exact
from sklearn.feature_extraction.text import TfidfVectorizer, ENGLISH_STOP_WORDS
from sklearn.decomposition import NMF

SEED = 42
os.makedirs("figures", exist_ok=True)
rec = pd.read_csv("screening_suggestions.csv", encoding="utf-8-sig", dtype=str).fillna("")
chartA = {json.loads(l)["record_id"]: json.loads(l) for l in open("charting_tierA_rows.jsonl")}
codes = pd.read_csv("charting_abstracts.csv", encoding="utf-8-sig", dtype=str).fillna("").set_index("record_id")

incA = [k for k, v in chartA.items() if v["final_decision"] == "include"]
tierB = rec[(rec.tier.str.startswith("B") | (rec.tier == "A+B")) & rec.suggestion.isin(["include", "maybe"])].record_id
tierB = [r for r in tierB if r not in chartA]
corpus = rec[rec.record_id.isin(set(incA) | set(tierB))].copy()
corpus["group"] = np.where(corpus.record_id.isin(incA), "Bangladesh", "Other South Asia")
corpus["year"] = pd.to_numeric(corpus.year, errors="coerce")
corpus["cited_by"] = pd.to_numeric(corpus.cited_by, errors="coerce").fillna(0)
corpus["text"] = (corpus.title + ". " + corpus.abstract).str.lower()

def ctry(rid):
    c = codes.loc[rid, "country"] if rid in codes.index else ""
    return c
corpus["country_tags"] = corpus.record_id.map(ctry)
def main_country(row):
    if row.group == "Bangladesh":
        return "Bangladesh"
    t = row.country_tags.split(";") if row.country_tags else []
    t = [x for x in t if x != "Bangladesh"]
    return t[0] if len(t) == 1 else ("Multi-country" if len(t) > 1 else "Unclear")
corpus["country"] = corpus.apply(main_country, axis=1)

out = ["# Paper 1 data-mining results", "",
       f"Corpus: {len(corpus)} included records ({(corpus.group=='Bangladesh').sum()} Bangladesh, "
       f"{(corpus.group!='Bangladesh').sum()} other South Asia). Generated by `scripts/mining.py` (seed {SEED}).", ""]

# ---------------- 1. Bibliometrics ----------------
yr = corpus[(corpus.year >= 2000) & (corpus.year <= 2026)]
tab = yr.groupby(["year", "group"]).size().unstack(fill_value=0)
ax = tab.plot(kind="bar", stacked=True, figsize=(10, 4.5), color=["#c0392b", "#7f8c8d"], width=0.85)
ax.set_xlabel("Publication year"); ax.set_ylabel("Records"); ax.set_title("Cybercrime research records by year")
plt.tight_layout(); plt.savefig("figures/fig1_trend.png", dpi=200); plt.close()
early = tab.loc[tab.index <= 2018].sum(); late = tab.loc[tab.index >= 2022].sum()
out += ["## 1. Growth", "", "| Period | Bangladesh | Other South Asia |", "|---|---|---|"]
for lab, lo, hi in (("≤2015", 0, 2015), ("2016–2018", 2016, 2018), ("2019–2021", 2019, 2021), ("2022–2024", 2022, 2024), ("2025–2026", 2025, 2026)):
    s = tab.loc[(tab.index >= lo) & (tab.index <= hi)].sum()
    out.append(f"| {lab} | {s.get('Bangladesh',0)} | {s.get('Other South Asia',0)} |")
share_recent = (corpus.year >= 2022).mean()
out += ["", f"{share_recent:.0%} of all included records were published in 2022 or later.", ""]

cc = corpus.country.value_counts()
out += ["### Records by country focus", "", "| Country | n | % |", "|---|---|---|"]
out += [f"| {k} | {v} | {v/len(corpus):.1%} |" for k, v in cc.items()]

out += ["", "### Document types", "", "| Type | Bangladesh | Other SA |", "|---|---|---|"]
dt = corpus.groupby(["type", "group"]).size().unstack(fill_value=0).sort_values("Bangladesh", ascending=False)
out += [f"| {k} | {r.get('Bangladesh',0)} | {r.get('Other South Asia',0)} |" for k, r in dt.iterrows()]

out += ["", "### OpenAlex field (top 10)", "", "| Field | Bangladesh | Other SA |", "|---|---|---|"]
fd = corpus.groupby(["field", "group"]).size().unstack(fill_value=0)
fd = fd.loc[fd.sum(1).sort_values(ascending=False).index[:10]]
out += [f"| {k or '(none)'} | {r.get('Bangladesh',0)} | {r.get('Other South Asia',0)} |" for k, r in fd.iterrows()]

out += ["", "### Top venues (Bangladesh records)", "", "| Venue | n |", "|---|---|"]
vb = corpus[corpus.group == "Bangladesh"].venue.replace("", "(none)").value_counts().head(12)
out += [f"| {k} | {v} |" for k, v in vb.items()]

bd = corpus[corpus.group == "Bangladesh"]
intl = bd.countries.apply(lambda s: len([c for c in s.split("; ") if c and c != "BD"]) > 0)
out += ["", f"International co-authorship (any non-BD author country) among Bangladesh records: {intl.mean():.0%} (n={intl.sum()}).",
        f"Median citations: Bangladesh {bd.cited_by.median():.0f}, other South Asia {corpus[corpus.group!='Bangladesh'].cited_by.median():.0f}. "
        f"Records never cited: Bangladesh {(bd.cited_by==0).mean():.0%}, other {(corpus[corpus.group!='Bangladesh'].cited_by==0).mean():.0%}.", ""]
top = bd.sort_values("cited_by", ascending=False).head(10)
out += ["### Most-cited Bangladesh records", "", "| ID | Year | Cites | Title |", "|---|---|---|---|"]
out += [f"| {r.record_id} | {int(r.year) if r.year==r.year else ''} | {int(r.cited_by)} | {r.title[:90]} |" for _, r in top.iterrows()]

# ---------------- 2. Topic model (NMF) ----------------
docs = corpus[corpus.abstract.str.len() > 50].copy()
extra = {"study", "paper", "research", "results", "findings", "using", "used", "based", "also", "however", "data",
         "analysis", "article", "approach", "proposed", "present", "use", "new", "chapter", "different", "various",
         "bangladesh", "india", "indian", "pakistan", "nepal", "sri", "lanka", "south", "asia", "asian", "country",
         "countries", "abstract", "et", "al", "2020", "2021", "2022", "2023", "2024", "2025", "2026"}
stop = list(ENGLISH_STOP_WORDS | extra)
vec = TfidfVectorizer(stop_words=stop, max_df=0.5, min_df=5, ngram_range=(1, 2), token_pattern=r"(?u)\b[a-z][a-z]+\b")
X = vec.fit_transform(docs.text)
terms = np.array(vec.get_feature_names_out())
K = 12
nmf = NMF(n_components=K, random_state=SEED, init="nndsvda", max_iter=600)
W = nmf.fit_transform(X); H = nmf.components_
docs["topic"] = W.argmax(1)
topwords = [", ".join(terms[H[k].argsort()[::-1][:10]]) for k in range(K)]
# Labels assigned by the authors after inspecting top terms (seed 42, k=12); re-check if the model changes.
LABELS = ["Cybercrime law & enforcement", "Cyberbullying: students & adolescents", "General cybercrime overviews",
          "Cybercrime against women", "Deepfakes", "Digital evidence & forensics", "Financial & banking fraud, scams",
          "AI-enabled crime", "Social media, platforms & hate", "Online harassment & journalists",
          "Bullying & children (reviews)", "IT law, privacy & rights"]
json.dump({"k": K, "topwords": topwords}, open("figures/topics.json", "w"), indent=1)
docs["period"] = pd.cut(docs.year, [0, 2018, 2022, 2030], labels=["≤2018", "2019–2022", "2023–2026"])
out += ["", "## 2. Topic model (NMF, k=12, TF-IDF of titles + abstracts)", "",
        f"{len(docs)} records with abstracts; vocabulary {len(terms)} terms (1–2-grams, min_df=5). Labels are assigned by the authors from the top terms.", "",
        "| # | Label | Top terms | n | % BD | ≤2018 | 2019–22 | 2023–26 |", "|---|---|---|---|---|---|---|---|"]
for k in range(K):
    d = docs[docs.topic == k]
    p = d.period.value_counts(normalize=True)
    out.append(f"| T{k+1} | {LABELS[k]} | {topwords[k]} | {len(d)} | {(d.group=='Bangladesh').mean():.0%} | {p.get('≤2018',0):.0%} | {p.get('2019–2022',0):.0%} | {p.get('2023–2026',0):.0%} |")
pt = docs.groupby(["period", "topic"], observed=False).size().unstack(fill_value=0)
pt = pt.div(pt.sum(1), axis=0)
pt.columns = LABELS
fig, ax = plt.subplots(figsize=(8, 6.5))
pt.T.iloc[::-1].plot(kind="barh", ax=ax, color=["#bdc3c7", "#7f8c8d", "#c0392b"], width=0.8)
ax.set_xlabel("Share of the period's records"); ax.set_ylabel("")
ax.set_title("Topic shares by period"); plt.tight_layout(); plt.savefig("figures/fig2_topics_period.png", dpi=200); plt.close()
docs[["record_id", "group", "year", "topic"]].to_csv("figures/topic_assignments.csv", index=False)

# ---------------- 3. Keyword co-occurrence network ----------------
GENERIC = {"like","examines","including","existing","need","significant","related","rapid","world","people","public","impact",
           "measures","information","technology","challenges","framework","issues","role","provide","current","way","ways",
           "growing","increasing","various","important","major","digital","online","internet","social","media","act","laws",
           "law","legal","crime","crimes","cyber","cybercrimes","cyber crime","cyber crimes","need","effective","potential"}
freq = np.asarray((X > 0).sum(0)).ravel()
cv_terms = [t for t in terms[freq.argsort()[::-1]] if t not in GENERIC and " " not in t or t in ("social media","online harassment","digital evidence","information technology","cyber bullying","artificial intelligence")][:40]
B = (X[:, [list(terms).index(t) for t in cv_terms]] > 0).astype(int)
C = (B.T @ B).toarray()
G = nx.Graph()
N = X.shape[0]
for i, j in itertools.combinations(range(len(cv_terms)), 2):
    assoc = C[i, j] * N / (C[i, i] * C[j, j])          # association strength (observed / expected)
    if C[i, j] >= 10 and assoc >= 1.6:
        G.add_edge(cv_terms[i], cv_terms[j], weight=assoc)
for i, t in enumerate(cv_terms):
    if t in G: G.nodes[t]["freq"] = C[i, i]
comm = nx.algorithms.community.greedy_modularity_communities(G, weight="weight")
cmap = {n: ci for ci, c in enumerate(comm) for n in c}
plt.figure(figsize=(11, 9)); pos = nx.spring_layout(G, seed=SEED, k=0.9, weight="weight")
nx.draw_networkx_edges(G, pos, alpha=0.15, width=[G[u][v]["weight"] / 1.5 for u, v in G.edges()])
nx.draw_networkx_nodes(G, pos, node_size=[G.nodes[n]["freq"] * 3 for n in G], node_color=[cmap[n] for n in G], cmap="tab10", alpha=0.85)
nx.draw_networkx_labels(G, pos, font_size=9); plt.axis("off"); plt.title("Term co-occurrence network (40 most frequent domain terms; links = association strength ≥1.6)")
plt.tight_layout(); plt.savefig("figures/fig3_network.png", dpi=200); plt.close()
out += ["", "## 3. Term co-occurrence network", "", f"{G.number_of_nodes()} terms, {G.number_of_edges()} links (≥10 co-occurrences and association strength ≥1.6); {len(comm)} clusters (greedy modularity):", ""]
out += [f"- Cluster {i+1}: {', '.join(sorted(c))}" for i, c in enumerate(comm)]

# ---------------- 4. Gap tests ----------------
out += ["", "## 4. Gap tests", ""]
a = pd.DataFrame([v for v in chartA.values() if v["final_decision"] == "include"])
def has(col, val): return a[col].str.contains(val, case=False, regex=False)
nA = len(a)
foc = {k: has("focus", k).sum() for k in ["law-policy", "victimisation", "prevention-awareness", "harm-impact", "speech regulation", "offending", "policing-investigation", "prosecution-courts-evidence", "detection-technical"]}
out += [f"### 4a. Bangladesh charted records (n={nA}): focus (multi-label)", "", "| Focus | n | % |", "|---|---|---|"]
out += [f"| {k} | {v} | {v/nA:.0%} |" for k, v in sorted(foc.items(), key=lambda x: -x[1])]
theory = a.theory.str.strip().str.lower()
named = ~theory.isin(["none", "", "nr"]) & ~theory.str.startswith("none")
crim = theory.str.contains("routine|lifestyle|strain|learning|neutrali|self-control|deterrence|rational|script|situational|procedural|labelling|fraud triangle|disinhibition|protection motivation|threat avoidance|social ecological", regex=True)
out += ["", f"Theory named: {named.sum()} ({named.mean():.0%}); criminological / behavioural theory named: {crim.sum()} ({crim.mean():.0%}).",
        f"Designs: " + ", ".join(f"{k} {v}" for k, v in a.design.str.split(" \\(").str[0].value_counts().items()), ""]
dsrc = {k: a.data_source.str.contains(k, case=False).sum() for k in ["survey", "interview", "legal", "news", "secondary", "social media", "technical", "official", "police"]}
out += ["Data sources (multi-label): " + ", ".join(f"{k} {v}" for k, v in dsrc.items()), ""]
gl = (a.gender_lens == "yes").mean()
out += [f"Gender lens: {gl:.0%}.", ""]
# chi-square: Bangladesh vs India vs Pakistan on rule-coded focus & theory (consistent coding across tiers)
# Tier B was searched in social-science fields only and pre-screened to records with a cybercrime term in
# the title, so the Bangladesh group is filtered the same way before comparison (like-for-like).
SOC = {"Social Sciences", "Psychology", "Arts and Humanities", "Business, Management and Accounting", "Economics, Econometrics and Finance"}
TITLE_TERM = re.compile(r"cyber|online fraud|internet fraud|scam|phish|hack|identity theft|data breach|ransomware|sextort|"
                        r"image-based|revenge porn|deepfake|online harassment|technology-facilitated|online gambling|"
                        r"digital security act|mobile money|mobile financial|bkash|nagad|digital payment|mobile banking", re.I)
matched_bd = corpus.group.eq("Bangladesh") & corpus.field.isin(SOC) & corpus.title.str.contains(TITLE_TERM)
cmp = corpus[((corpus.country.isin(["India", "Pakistan"])) | matched_bd) & (corpus.abstract.str.len() > 50)].copy()
cmp = cmp.join(codes[["focus", "design", "theory"]], on="record_id")
out += ["### 4b. Bangladesh vs India vs Pakistan (rule-based abstract codes; chi-square tests)", "",
        f"Like-for-like: Bangladesh records restricted to the Tier B eligibility (social-science fields, cybercrime term in title): n={matched_bd.sum()} of {(corpus.group=='Bangladesh').sum()}.", "",
        "| Indicator | Bangladesh | India | Pakistan | χ² | p |", "|---|---|---|---|---|---|"]
for lab, col, pat in (("Offending focus", "focus", "offending"), ("Victimisation focus", "focus", "victimisation"),
                      ("Policing focus", "focus", "policing"), ("Law/policy focus", "focus", "law_policy"),
                      ("Legal-doctrinal design", "design", "legal_doctrinal"), ("Survey design", "design", "survey"),
                      ("Criminological theory named", "theory", ".")):
    flag = cmp[col].fillna("").str.contains(pat)
    ct = pd.crosstab(cmp.country, flag).reindex(["Bangladesh", "India", "Pakistan"]).fillna(0)
    if ct.shape[1] < 2: continue
    chi, p, _, _ = chi2_contingency(ct)
    sh = (ct[True] / ct.sum(1))
    out.append(f"| {lab} | {sh['Bangladesh']:.0%} | {sh['India']:.0%} | {sh['Pakistan']:.0%} | {chi:.1f} | {p:.3f} |")
out += ["", "n: " + ", ".join(f"{k} {v}" for k, v in cmp.country.value_counts().items()), ""]
# focus distribution figure for Bangladesh
fig, ax = plt.subplots(figsize=(8, 4))
s = pd.Series(foc).sort_values()
ax.barh(s.index, s.values / nA * 100, color=["#c0392b" if k in ("offending", "policing-investigation", "prosecution-courts-evidence") else "#7f8c8d" for k in s.index])
ax.set_xlabel("% of included Bangladesh records"); ax.set_title(f"Research focus, Bangladesh (n={nA})")
plt.tight_layout(); plt.savefig("figures/fig4_focus_bd.png", dpi=200); plt.close()

open("mining_results.md", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("\n".join(out[:6])); print("done")
